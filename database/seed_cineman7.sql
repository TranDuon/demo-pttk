DROP DATABASE IF EXISTS cineman7;
CREATE DATABASE cineman7 CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE cineman7;

CREATE TABLE tblUser7 (
  id INT AUTO_INCREMENT PRIMARY KEY,
  username VARCHAR(50) NOT NULL UNIQUE,
  password VARCHAR(255) NOT NULL,
  fullName VARCHAR(100) NOT NULL
);
CREATE TABLE tblCustomer7 (
  userId INT PRIMARY KEY,
  phoneNumber VARCHAR(15) NOT NULL UNIQUE,
  email VARCHAR(100) NOT NULL UNIQUE,
  dateOfBirth DATE NOT NULL,
  cardCode VARCHAR(20) NOT NULL UNIQUE,
  points INT NOT NULL DEFAULT 0,
  issueDate DATE NOT NULL,
  FOREIGN KEY (userId) REFERENCES tblUser7(id)
);
CREATE TABLE tblSalesStaff7 (
  userId INT PRIMARY KEY,
  FOREIGN KEY (userId) REFERENCES tblUser7(id)
);
CREATE TABLE tblManager7 (
  userId INT PRIMARY KEY,
  FOREIGN KEY (userId) REFERENCES tblUser7(id)
);
CREATE TABLE tblMovie7 (
  id INT AUTO_INCREMENT PRIMARY KEY,
  title VARCHAR(200) NOT NULL,
  genre VARCHAR(50),
  duration INT NOT NULL,
  director VARCHAR(100),
  description TEXT
);
CREATE TABLE tblRoom7 (
  id INT AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(50) NOT NULL UNIQUE
);
CREATE TABLE tblSeat7 (
  id INT AUTO_INCREMENT PRIMARY KEY,
  seatRow VARCHAR(2) NOT NULL,
  seatNumber INT NOT NULL,
  roomId INT NOT NULL,
  UNIQUE (roomId, seatRow, seatNumber),
  FOREIGN KEY (roomId) REFERENCES tblRoom7(id)
);
CREATE TABLE tblShowtime7 (
  id INT AUTO_INCREMENT PRIMARY KEY,
  showDate DATE NOT NULL,
  startTime TIME NOT NULL,
  ticketPrice DECIMAL(12,2) NOT NULL CHECK (ticketPrice > 0),
  movieId INT NOT NULL,
  roomId INT NOT NULL,
  managerId INT NOT NULL,
  FOREIGN KEY (movieId) REFERENCES tblMovie7(id),
  FOREIGN KEY (roomId) REFERENCES tblRoom7(id),
  FOREIGN KEY (managerId) REFERENCES tblManager7(userId)
);
CREATE TABLE tblInvoice7 (
  id INT AUTO_INCREMENT PRIMARY KEY,
  createdTime DATETIME NOT NULL,
  customerId INT NULL,
  salesStaffId INT NULL,
  CHECK (customerId IS NOT NULL OR salesStaffId IS NOT NULL),
  FOREIGN KEY (customerId) REFERENCES tblCustomer7(userId),
  FOREIGN KEY (salesStaffId) REFERENCES tblSalesStaff7(userId)
);
CREATE TABLE tblTicket7 (
  id INT AUTO_INCREMENT PRIMARY KEY,
  price DECIMAL(12,2) NOT NULL,
  showtimeId INT NOT NULL,
  seatId INT NOT NULL,
  invoiceId INT NOT NULL,
  UNIQUE (showtimeId, seatId),
  FOREIGN KEY (showtimeId) REFERENCES tblShowtime7(id),
  FOREIGN KEY (seatId) REFERENCES tblSeat7(id),
  FOREIGN KEY (invoiceId) REFERENCES tblInvoice7(id)
);

